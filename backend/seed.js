async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to MongoDB');

    // Clear existing data
    await User.deleteMany({});
    await Recipe.deleteMany({});
    console.log('Cleared existing users and recipes');

    // Create users
    const salt = await bcrypt.genSalt(10);
    const hashedPassword = await bcrypt.hash('password123', salt);

    const createdUsers = await User.insertMany(
      users.map(u => ({ ...u, password: hashedPassword }))
    );
    console.log(`Created ${createdUsers.length} users`);

    // Assign recipes round-robin across users
    const recipesWithOwners = recipes.map((recipe, i) => ({
      ...recipe,
      createdBy: createdUsers[i % createdUsers.length]._id,
    }));

    const createdRecipes = await Recipe.insertMany(recipesWithOwners);
    console.log(`Created ${createdRecipes.length} recipes`);

    console.log('\nSeed complete!');
    console.log('User credentials: email from list above, password: password123');
  } catch (err) {
    console.error('Seed failed:', err);
  } finally {
    await mongoose.disconnect();
  }
}

seed();
